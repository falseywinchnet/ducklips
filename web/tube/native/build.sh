#!/bin/sh
set -eu
cd "$(dirname "$0")/../../.."
TASK_CLANG=${DUCKLIPS_CLANG:-/opt/homebrew/opt/llvm/bin/clang}
TASK_LINKER=${DUCKLIPS_WASM_LD:-"$(rustc --print sysroot)/lib/rustlib/aarch64-apple-darwin/bin/rust-lld"}
TASK_TMP=$(mktemp -d)
trap 'rm -rf "$TASK_TMP"' EXIT
"$TASK_CLANG" --target=wasm32 -O3 -ffp-contract=off -fno-builtin -nostdlib -c web/tube/native/core.c -o "$TASK_TMP/core.o"
DYLD_LIBRARY_PATH="$(rustc --print sysroot)/lib" "$TASK_LINKER" -flavor wasm --no-entry --export=step --export=walls_prepare --export=walls_finish --export=walls_prepare_batch --export=walls_finish_batch --export=base --export-memory --initial-memory=16777216 --max-memory=16777216 "$TASK_TMP/core.o" -o "$TASK_TMP/core.wasm"
python3 - "$TASK_TMP/core.wasm" <<'PY'
import pathlib,sys,hashlib
b=pathlib.Path(sys.argv[1]).read_bytes()
p=pathlib.Path('web/tube/core-wasm.mjs')
p.write_text('// Generated by native/build.sh from native/core.c.\n// wasm sha256: '+hashlib.sha256(b).hexdigest()+'\nconst bytes=new Uint8Array(['+','.join(map(str,b))+']);\nexport const coreModule=new WebAssembly.Module(bytes);\n')
print('Built',len(b),'WASM bytes')
PY
